const LANG_KEY = "hdx-lang";

const bySelector = (selector) => Array.from(document.querySelectorAll(selector));

const HERO_INTERVAL = 6500;

const heroState = {
  root: null,
  title: null,
  lead: null,
  panelTag: null,
  panelTitle: null,
  panelDesc: null,
  chips: [],
  bgLayers: [],
  dotsWrap: null,
  dots: [],
  prevBtn: null,
  nextBtn: null,
  slides: [],
  index: 0,
  bgIndex: 0,
  timer: null,
  prefersReduced: false,
  touchStartX: 0,
  touchStartY: 0,
  touchActive: false
};

const getHeroSlides = (lang) => translations[lang]?.heroSlides ?? translations.zh.heroSlides ?? [];

const cacheHeroElements = () => {
  heroState.title = heroState.root.querySelector("[data-hero-title]");
  heroState.lead = heroState.root.querySelector("[data-hero-lead]");
  heroState.panelTag = heroState.root.querySelector("[data-hero-panel-tag]");
  heroState.panelTitle = heroState.root.querySelector("[data-hero-panel-title]");
  heroState.panelDesc = heroState.root.querySelector("[data-hero-panel-desc]");
  heroState.chips = Array.from(heroState.root.querySelectorAll("[data-hero-chip]"));
  heroState.bgLayers = Array.from(heroState.root.querySelectorAll("[data-hero-bg]"));
  heroState.dotsWrap = heroState.root.querySelector("[data-hero-dots]");
  heroState.prevBtn = heroState.root.querySelector("[data-hero-prev]");
  heroState.nextBtn = heroState.root.querySelector("[data-hero-next]");
};

const setHeroBackground = (image, immediate) => {
  if (!heroState.bgLayers.length) return;
  if (immediate) {
    heroState.bgLayers.forEach((layer, idx) => {
      layer.style.backgroundImage = `url('${image}')`;
      layer.classList.toggle("is-active", idx === 0);
    });
    heroState.bgIndex = 0;
    return;
  }
  const nextIndex = heroState.bgIndex === 0 ? 1 : 0;
  const nextLayer = heroState.bgLayers[nextIndex];
  const activeLayer = heroState.bgLayers[heroState.bgIndex];
  nextLayer.style.backgroundImage = `url('${image}')`;
  nextLayer.classList.add("is-active");
  activeLayer.classList.remove("is-active");
  heroState.bgIndex = nextIndex;
};

const updateHeroDots = () => {
  heroState.dots.forEach((dot, idx) => {
    dot.classList.toggle("is-active", idx === heroState.index);
  });
};

const renderHeroDots = () => {
  if (!heroState.dotsWrap) return;
  heroState.dotsWrap.innerHTML = heroState.slides
    .map(
      (_, idx) =>
        `<button type="button" class="hero-dot" data-hero-dot="${idx}" aria-label="Slide ${idx + 1}"></button>`
    )
    .join("");
  heroState.dots = Array.from(heroState.dotsWrap.querySelectorAll(".hero-dot"));
  heroState.dots.forEach((dot) => {
    dot.addEventListener("click", () => {
      const index = Number(dot.dataset.heroDot);
      showHeroSlide(index);
      restartHeroAutoplay();
    });
  });
};

const showHeroSlide = (index, immediate = false) => {
  const count = heroState.slides.length;
  if (!count) return;
  const safeIndex = ((index % count) + count) % count;
  heroState.index = safeIndex;
  const slide = heroState.slides[safeIndex];
  if (heroState.title) heroState.title.textContent = slide.title;
  if (heroState.lead) heroState.lead.textContent = slide.lead;
  if (heroState.panelTag) heroState.panelTag.textContent = slide.panel.tag;
  if (heroState.panelTitle) heroState.panelTitle.textContent = slide.panel.title;
  if (heroState.panelDesc) heroState.panelDesc.textContent = slide.panel.desc;
  heroState.chips.forEach((chip, idx) => {
    const text = slide.panel.chips[idx];
    if (text) {
      chip.textContent = text;
      chip.style.display = "inline-flex";
    } else {
      chip.style.display = "none";
    }
  });
  setHeroBackground(slide.image, immediate);
  updateHeroDots();
};

const stopHeroAutoplay = () => {
  if (heroState.timer) {
    clearInterval(heroState.timer);
    heroState.timer = null;
  }
};

const startHeroAutoplay = () => {
  if (!heroState.root || heroState.prefersReduced) return;
  stopHeroAutoplay();
  heroState.timer = setInterval(() => {
    showHeroSlide(heroState.index + 1);
  }, HERO_INTERVAL);
};

const restartHeroAutoplay = () => {
  stopHeroAutoplay();
  startHeroAutoplay();
};

const updateHeroLanguage = (lang, immediate = false) => {
  if (!heroState.root) return;
  heroState.slides = getHeroSlides(lang);
  renderHeroDots();
  if (heroState.index >= heroState.slides.length) heroState.index = 0;
  showHeroSlide(heroState.index, immediate);
};

const initHeroSlider = (lang) => {
  heroState.root = document.querySelector(".hero-slider");
  if (!heroState.root) return;
  cacheHeroElements();
  heroState.prefersReduced = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  updateHeroLanguage(lang, true);
  if (heroState.prevBtn) {
    heroState.prevBtn.addEventListener("click", () => {
      showHeroSlide(heroState.index - 1);
      restartHeroAutoplay();
    });
  }
  if (heroState.nextBtn) {
    heroState.nextBtn.addEventListener("click", () => {
      showHeroSlide(heroState.index + 1);
      restartHeroAutoplay();
    });
  }
  heroState.root.addEventListener("mouseenter", stopHeroAutoplay);
  heroState.root.addEventListener("mouseleave", startHeroAutoplay);
  heroState.root.addEventListener("focusin", stopHeroAutoplay);
  heroState.root.addEventListener("focusout", startHeroAutoplay);
  initHeroSwipe();
  startHeroAutoplay();
};

const initHeroSwipe = () => {
  if (!heroState.root) return;
  const threshold = 40;
  const isHorizontalSwipe = (dx, dy) => Math.abs(dx) > threshold && Math.abs(dx) > Math.abs(dy) * 1.2;

  heroState.root.addEventListener(
    "touchstart",
    (event) => {
      if (event.touches.length !== 1) return;
      heroState.touchActive = true;
      heroState.touchStartX = event.touches[0].clientX;
      heroState.touchStartY = event.touches[0].clientY;
    },
    { passive: true }
  );

  heroState.root.addEventListener(
    "touchend",
    (event) => {
      if (!heroState.touchActive) return;
      heroState.touchActive = false;
      if (!event.changedTouches.length) return;
      const dx = event.changedTouches[0].clientX - heroState.touchStartX;
      const dy = event.changedTouches[0].clientY - heroState.touchStartY;
      if (!isHorizontalSwipe(dx, dy)) return;
      if (dx > 0) {
        showHeroSlide(heroState.index - 1);
      } else {
        showHeroSlide(heroState.index + 1);
      }
      restartHeroAutoplay();
    },
    { passive: true }
  );

  heroState.root.addEventListener(
    "touchcancel",
    () => {
      heroState.touchActive = false;
    },
    { passive: true }
  );
};

const detectLang = () => {
  const saved = localStorage.getItem(LANG_KEY);
  if (saved && translations[saved]) return saved;
  const navLang = navigator.language?.toLowerCase() ?? "";
  if (navLang.startsWith("vi")) return "vi";
  return "zh";
};

const applyTranslations = (lang) => {
  const dict = translations[lang] ?? translations.zh;
  document.documentElement.lang = lang === "vi" ? "vi" : "zh-Hant";
  document.title = dict.title;

  bySelector("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  bySelector("[data-i18n-attr]").forEach((el) => {
    const raw = el.dataset.i18nAttr || "";
    const [attr, key] = raw.split(":");
    if (!attr || !key) return;
    if (dict[key]) {
      el.setAttribute(attr, dict[key]);
    }
  });

  updateHeroLanguage(lang, true);

  bySelector(".lang-btn").forEach((btn) => {
    const active = btn.dataset.lang === lang;
    btn.classList.toggle("active", active);
    btn.setAttribute("aria-pressed", active ? "true" : "false");
  });
};

const initLanguageSwitcher = () => {
  const buttons = bySelector(".lang-btn");
  buttons.forEach((btn) => {
    btn.addEventListener("click", () => {
      const lang = btn.dataset.lang;
      if (!translations[lang]) return;
      localStorage.setItem(LANG_KEY, lang);
      applyTranslations(lang);
    });
  });
};

const initReveal = () => {
  const revealItems = bySelector(".reveal");
  if (!revealItems.length) return;
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.2 }
  );

  revealItems.forEach((item) => observer.observe(item));
};

const init = () => {
  const lang = detectLang();
  applyTranslations(lang);
  initHeroSlider(lang);
  initLanguageSwitcher();
  initReveal();
};

document.addEventListener("DOMContentLoaded", init);
