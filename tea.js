const slides = Array.from(document.querySelectorAll(".hero-slide"));
let slideIndex = 0;

function showSlide(index) {
  if (!slides.length) return;
  slideIndex = (index + slides.length) % slides.length;
  slides.forEach((slide, idx) => {
    slide.classList.toggle("is-active", idx === slideIndex);
  });
}

function initHero() {
  if (slides.length < 2) return;
  setInterval(() => showSlide(slideIndex + 1), 4800);
}

function applyLanguage(lang) {
  const dict = translations[lang] || translations.zh;
  document.documentElement.lang = lang === "vi" ? "vi" : "zh-Hant";
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    if (dict[key]) node.textContent = dict[key];
  });
  document.querySelectorAll(".lang-btn").forEach((button) => {
    button.classList.toggle("active", button.dataset.lang === lang);
  });
  localStorage.setItem("huang-tea-lang", lang);
}

function initLanguage() {
  const saved = localStorage.getItem("huang-tea-lang") || "zh";
  applyLanguage(saved);
  document.querySelectorAll(".lang-btn").forEach((button) => {
    button.addEventListener("click", () => applyLanguage(button.dataset.lang));
  });
}

function initReveal() {
  const items = Array.from(document.querySelectorAll(".reveal"));
  if (!items.length) return;
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.18 }
  );
  items.forEach((item) => observer.observe(item));
}

document.addEventListener("DOMContentLoaded", () => {
  initLanguage();
  initHero();
  initReveal();
});
